// Verify hashes and run the packaged executable with a fresh, isolated profile.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const { listArchiveFiles, extractArchiveFile } = require('./archive-files.cjs');
const { getBuildOptions, getPackageFiles, validateInputs, executableName, getLegalCopyPlan, assertElectronVersion } = require('./build-portable.cjs');
const root = path.resolve(__dirname, '..');
const directory = path.resolve(process.argv[2] || getBuildOptions(root).output);
const report = JSON.parse(fs.readFileSync(path.join(directory, 'build-report.json')));
const archive = path.join(directory, 'resources/app.asar');
const executable = path.join(directory, executableName);
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(process.platform, 'win32', 'Packaged verification supports Windows only');
assert.equal(report.version, '1.0.38');
assertElectronVersion(report.electronVersion);
assert.equal(report.executable, executableName);
assert.equal(sha(fs.readFileSync(archive)), report.asarSha256, 'Archive changed since build');
assert.equal(sha(fs.readFileSync(executable)), report.exeSha256, 'Executable changed since build');
const runtime = path.join(path.dirname(require.resolve('electron/package.json')), 'dist');
assertElectronVersion(require('electron/package.json').version);
for (const name of ['LICENSE', 'LICENSES.chromium.html']) assert.equal(sha(fs.readFileSync(path.join(directory, name))), sha(fs.readFileSync(path.join(runtime, name))), 'Runtime license changed: ' + name);
for (const { source, destination } of getLegalCopyPlan()) assert.equal(sha(fs.readFileSync(path.join(directory, destination))), sha(fs.readFileSync(path.join(root, source))), 'Application license differs: ' + destination);
const metadata = JSON.parse(extractArchiveFile(archive, 'package.json'));
assert.equal(metadata.version, '1.0.38');
assert.equal(metadata.pairedThemeTrialBuild, true);
assert.equal(metadata.skinTrialBuild, undefined);
const expected = getPackageFiles(root).sort();
const entries = listArchiveFiles(archive);
assert.deepEqual(entries, expected, 'Archive must match the exact packaging allow-list');
assert.deepEqual(report.files.map(item => item.file).sort(), expected);
for (const relative of expected) {
  const hash = sha(extractArchiveFile(archive, relative));
  assert.equal(hash, sha(fs.readFileSync(path.join(root, relative))), 'Package differs: ' + relative);
  assert.equal(hash, report.files.find(item => item.file === relative).sha256, 'Recorded hash differs: ' + relative);
}
validateInputs(root);
fs.mkdirSync(path.join(root, 'artifacts'), { recursive: true });
const output = fs.mkdtempSync(path.join(root, 'artifacts', 'packaged-smoke-'));
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawnSync(executable, ['--smoke-test', '--smoke-all-themes'], { cwd: output, env, windowsHide: true, encoding: 'utf8', timeout: 180000 });
if (child.stdout) process.stdout.write(child.stdout);
if (child.stderr) process.stderr.write(child.stderr);
assert.ifError(child.error);
assert.equal(child.status, 0, 'Packaged smoke failed');
const smoke = JSON.parse(fs.readFileSync(path.join(output, 'artifacts/smoke-reminder-report.json')));
assert.equal(smoke.version, metadata.version);
assert.equal(Object.keys(smoke.checks).length, 64, 'Expected all 64 real runtime checks');
assert.ok(Object.values(smoke.checks).every(value => value === true), 'Runtime checks must all pass');
const { COMPANION_THEMES } = require('../src/companion-themes');
assert.deepEqual(smoke.themes.map(t => t.id), COMPANION_THEMES.map(t => t.id));
smoke.themes.forEach((theme, index) => {
  for (const key of ['workAssetId', 'restAssetId', 'restPackId']) assert.equal(theme[key], COMPANION_THEMES[index][key]);
  assert.equal(theme.nextThemeId, COMPANION_THEMES[(index + 1) % 10].id);
  for (const suffix of ['Work', 'Card', 'Pause', 'Collapse', 'Advance', 'Undo']) assert.equal(smoke.checks[theme.id + suffix], true);
  for (const suffix of ['work', 'rest', 'card']) assert.ok(fs.statSync(path.join(output, 'artifacts', theme.id + '-' + suffix + '.png')).size > 0);
});
assert.equal(smoke.checks.allThemesReturnCloud, true);
assert.equal(smoke.appearance.themeId, 'cloud');
assert.equal(smoke.mainBounds.width, 270);
assert.equal(smoke.mainBounds.height, 106);
assert.equal(smoke.userData, path.join(output, 'artifacts/smoke-profile'));
const summary = { allPassed: true, version: metadata.version, matchedPackagedFiles: expected.length, runtimeChecks: 64, directory, smokeUserData: smoke.userData, asarSha256: report.asarSha256, exeSha256: report.exeSha256 };
fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify(summary, null, 2) + '\n');
console.log(JSON.stringify(summary, null, 2));
