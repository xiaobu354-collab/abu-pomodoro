function freezeVariant(lines) {
  return Object.freeze(Object.fromEntries(['start', 'running', 'finished'].map((phase, index) =>
    [phase, Object.freeze({ title: lines[index][0], body: lines[index][1] })])));
}

const REMINDER_PACKS = Object.freeze(rawPacks.map(([id, file, start, running, finished]) => {
  const [name, second, third] = extraCopy[id];
  const variants = Object.freeze([[start, running, finished], second, third].map(freezeVariant));
  return Object.freeze({ id, name, image: `../../assets/rest-reminders/${file}`, variants,
    variantIndex: 0, ...variants[0] });
}));
const REMINDER_PACK_IDS = Object.freeze(REMINDER_PACKS.map(({ id }) => id));
const DEFAULT_REMINDER_PACK_ID = 'window-tea';
const byId = new Map(REMINDER_PACKS.map((pack) => [pack.id, pack]));
function getReminderPack(id, variantIndex = 0) {
  const pack = byId.get(id) || byId.get(DEFAULT_REMINDER_PACK_ID);
  const index = Number.isInteger(variantIndex) && variantIndex >= 0 && variantIndex < pack.variants.length
    ? variantIndex : 0;
  return index === 0 ? pack : Object.freeze({ ...pack, ...pack.variants[index], variantIndex: index });
}

module.exports = { REMINDER_PACKS, REMINDER_PACK_IDS, DEFAULT_REMINDER_PACK_ID, getReminderPack };
